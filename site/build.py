"""Bundle intro.md and every apps/day-*/README.md into content.js for the calendar site.

Run from anywhere:  python3 site/build.py
If the SITE_PASSWORD environment variable is set, the content is encrypted with it
(AES-256-GCM, PBKDF2-SHA256 key) and needs the `cryptography` package.
"""
import base64
import hashlib
import json
import os
import re
from pathlib import Path

SITE = Path(__file__).resolve().parent
ROOT = SITE.parent
ITERATIONS = 250_000


def read_icon(app_dir):
    app_yaml = app_dir / "app.yaml"
    if app_yaml.exists():
        match = re.search(r"^icon:\s*(.+)$", app_yaml.read_text(encoding="utf-8"), re.M)
        if match:
            return match.group(1).strip()
    return "🎁"


def split_title(markdown):
    lines = markdown.splitlines()
    title = lines[0].lstrip("# ").strip() if lines and lines[0].startswith("# ") else ""
    body = "\n".join(lines[1:]).lstrip() if title else markdown
    return title, body


entries = []

title, body = split_title((SITE / "intro.md").read_text(encoding="utf-8"))
entries.append({"day": 0, "title": title, "icon": "🎄", "markdown": body, "zip": None})

for app_dir in sorted((ROOT / "apps").glob("day-*")):
    day = int(app_dir.name.split("-")[1])
    title, body = split_title((app_dir / "README.md").read_text(encoding="utf-8"))
    title = re.sub(r"^Day \d+ - ", "", title)
    entries.append({
        "day": day,
        "title": title,
        "icon": read_icon(app_dir),
        "markdown": body,
        "zip": f"../zips/{app_dir.name}.zip",
    })

payload = json.dumps(entries, ensure_ascii=False)
password = os.environ.get("SITE_PASSWORD")

if password:
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    salt, iv = os.urandom(16), os.urandom(12)
    key = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS, dklen=32)
    data = AESGCM(key).encrypt(iv, payload.encode(), None)
    b64 = lambda b: base64.b64encode(b).decode()
    box = {"salt": b64(salt), "iv": b64(iv), "iterations": ITERATIONS, "data": b64(data)}
    js = "window.CALENDAR_ENCRYPTED = " + json.dumps(box) + ";\n"
else:
    js = "window.CALENDAR = " + payload + ";\n"

(SITE / "content.js").write_text("// Generated by build.py - do not edit by hand.\n" + js, encoding="utf-8")
print(f"Wrote {len(entries)} entries to {SITE / 'content.js'} ({'encrypted' if password else 'plain'})")
