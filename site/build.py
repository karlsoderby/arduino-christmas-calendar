"""Bundle intro.md and every apps/day-*/README.md into content.js for the calendar site.

Run from anywhere:  python3 site/build.py
"""
import json
import re
from pathlib import Path

SITE = Path(__file__).resolve().parent
ROOT = SITE.parent


def read_icon(app_dir):
    app_yaml = app_dir / "app.yaml"
    if app_yaml.exists():
        match = re.search(r"^icon:\s*(.+)$", app_yaml.read_text(encoding="utf-8"), re.M)
        if match:
            return match.group(1).strip()
    return "🎁"


def split_title(markdown):
    lines = markdown.splitlines()
    title = lines[0].lstrip("# ").strip() if lines and lines[0].startswith("# ") else ""
    body = "\n".join(lines[1:]).lstrip() if title else markdown
    return title, body


entries = []

title, body = split_title((SITE / "intro.md").read_text(encoding="utf-8"))
entries.append({"day": 0, "title": title, "icon": "🎄", "markdown": body, "zip": None})

for app_dir in sorted((ROOT / "apps").glob("day-*")):
    day = int(app_dir.name.split("-")[1])
    title, body = split_title((app_dir / "README.md").read_text(encoding="utf-8"))
    title = re.sub(r"^Day \d+ - ", "", title)
    entries.append({
        "day": day,
        "title": title,
        "icon": read_icon(app_dir),
        "markdown": body,
        "zip": f"../zips/{app_dir.name}.zip",
    })

(SITE / "content.js").write_text(
    "// Generated by build.py - do not edit by hand.\nwindow.CALENDAR = "
    + json.dumps(entries, ensure_ascii=False, indent=1)
    + ";\n",
    encoding="utf-8",
)
print(f"Wrote {len(entries)} entries to {SITE / 'content.js'}")
